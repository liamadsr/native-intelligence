-- Writes SQL that re-creates what the app itself added inside the schemas a
-- Supabase project manages (auth, storage, realtime): row-level-security
-- policies on their tables, and triggers on their tables that call a function
-- of the app's.
--
-- Why this exists. `supabase db dump` leaves those schemas out of schema.sql
-- (--exclude-schema), because the Auth, Storage and Realtime services create
-- their own tables. A policy or a trigger belongs to its table, so it is left
-- out with it, and nothing in Supabase's restore guide puts it back. For this
-- app that is the two triggers on auth.users that set up a new account, the
-- policies on storage.objects, and the private-channel policies on
-- realtime.messages.
--
-- It also writes the pg_cron jobs. pg_dump does not dump cron.job (it is a
-- table of the extension, not of the app), so data.sql has no jobs in it.
--
-- Run on the SOURCE by 01-dump.sh (read-only); the output is extras.sql,
-- applied to the target by 02-restore.sh. Each statement replaces an object of
-- the same name, so applying it twice is harmless.
--
-- :managed is the quoted, comma-separated schema list from lib.sh.

-- Fully qualified names in everything the catalog functions print.
set search_path = '';

select '-- Generated by 01-dump.sh from the source database. Do not edit.';
select 'set search_path = '''';';

select '-- Policies on tables in auth, storage and realtime.'
union all
select '-- (none)' where not exists (
  select 1 from pg_catalog.pg_policy pol
  join pg_catalog.pg_class c on c.oid = pol.polrelid
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  where n.nspname in (:managed));

select pg_catalog.format(
         E'drop policy if exists %I on %I.%I;\ncreate policy %I on %I.%I as %s for %s to %s%s%s;',
         pol.polname, n.nspname, c.relname,
         pol.polname, n.nspname, c.relname,
         case when pol.polpermissive then 'permissive' else 'restrictive' end,
         case pol.polcmd
           when 'r' then 'select' when 'a' then 'insert'
           when 'w' then 'update' when 'd' then 'delete' else 'all'
         end,
         (select pg_catalog.string_agg(
                   case when r.roleid = 0 then 'public'
                        else pg_catalog.quote_ident(pg_catalog.pg_get_userbyid(r.roleid)) end,
                   ', ' order by r.roleid)
          from pg_catalog.unnest(pol.polroles) as r(roleid)),
         case when pol.polqual is not null
              then E'\n  using (' || pg_catalog.pg_get_expr(pol.polqual, pol.polrelid) || ')'
              else '' end,
         case when pol.polwithcheck is not null
              then E'\n  with check (' || pg_catalog.pg_get_expr(pol.polwithcheck, pol.polrelid) || ')'
              else '' end)
from pg_catalog.pg_policy pol
join pg_catalog.pg_class c on c.oid = pol.polrelid
join pg_catalog.pg_namespace n on n.oid = c.relnamespace
where n.nspname in (:managed)
order by n.nspname, c.relname, pol.polname;

select '-- Triggers on those tables that call a function outside those schemas.'
union all
select '-- (none)' where not exists (
  select 1 from pg_catalog.pg_trigger t
  join pg_catalog.pg_class c on c.oid = t.tgrelid
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  join pg_catalog.pg_proc p on p.oid = t.tgfoid
  join pg_catalog.pg_namespace pn on pn.oid = p.pronamespace
  where not t.tgisinternal and n.nspname in (:managed) and pn.nspname not in (:managed));

select pg_catalog.regexp_replace(pg_catalog.pg_get_triggerdef(t.oid, false), '^CREATE TRIGGER', 'create or replace trigger')
       || ';'
       || case t.tgenabled
            when 'D' then pg_catalog.format(E'\nalter table %I.%I disable trigger %I;', n.nspname, c.relname, t.tgname)
            when 'A' then pg_catalog.format(E'\nalter table %I.%I enable always trigger %I;', n.nspname, c.relname, t.tgname)
            when 'R' then pg_catalog.format(E'\nalter table %I.%I enable replica trigger %I;', n.nspname, c.relname, t.tgname)
            else ''
          end
from pg_catalog.pg_trigger t
join pg_catalog.pg_class c on c.oid = t.tgrelid
join pg_catalog.pg_namespace n on n.oid = c.relnamespace
join pg_catalog.pg_proc p on p.oid = t.tgfoid
join pg_catalog.pg_namespace pn on pn.oid = p.pronamespace
where not t.tgisinternal
  and n.nspname in (:managed)
  and pn.nspname not in (:managed)
order by n.nspname, c.relname, t.tgname;

-- pg_cron jobs. cron.schedule() with a name replaces a job of that name.
select '-- pg_cron jobs.'
where exists (select 1 from pg_catalog.pg_extension where extname = 'pg_cron');
\if :has_cron
select case
         when j.jobname is null
           then pg_catalog.format('select cron.schedule(%L, %L);', j.schedule, j.command)
         else pg_catalog.format('select cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command)
       end
       || case when j.active then ''
               else pg_catalog.format(
                 E'\nselect cron.alter_job(jobid, active := false) from cron.job where jobname is not distinct from %L and command = %L;',
                 j.jobname, j.command)
          end
       || case when j.username <> 'postgres' or j.database <> pg_catalog.current_database()
               then pg_catalog.format(E'\n-- NOTE: on the source this job ran as %I in database %I.', j.username, j.database)
               else '' end
from cron.job j
order by j.jobid;
\endif
