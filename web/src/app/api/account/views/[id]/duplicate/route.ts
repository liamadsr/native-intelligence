import { createClient } from '@/lib/supabase/server'
import { getCurrentWorkspaceId } from '@/lib/workspace'
import { NextResponse, type NextRequest } from 'next/server'

// POST /api/account/views/[id]/duplicate — Duplicate a view
export async function POST(
  _request: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  const supabase = await createClient()
  const {
    data: { user },
  } = await supabase.auth.getUser()
  if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

  const workspaceId = await getCurrentWorkspaceId()
  if (!workspaceId) return NextResponse.json({ error: 'No workspace' }, { status: 400 })

  // Fetch the original view
  const { data: original, error: fetchError } = await supabase
    .from('view')
    .select('*')
    .eq('id', id)
    .eq('workspace_id', workspaceId)
    .single()

  if (fetchError || !original) {
    return NextResponse.json({ error: 'View not found' }, { status: 404 })
  }

  // Create the duplicate with new name, personal visibility, and null slug (auto-generated)
  const { data: duplicate, error } = await supabase
    .from('view')
    .insert({
      workspace_id: workspaceId,
      team_id: original.team_id,
      created_by: user.id,
      name: `${original.name} (copy)`,
      description: original.description,
      icon: original.icon,
      color: original.color,
      slug: null, // auto-generated by trigger
      entity_type: original.entity_type,
      // Keep the copy in the scope it was duplicated from (a project's /
      // contact's views); a null scope would make it a global view.
      scope_type: original.scope_type,
      scope_id: original.scope_id,
      visibility: 'personal',
      layout: original.layout,
      filters: original.filters,
      grouping: original.grouping,
      sub_grouping: original.sub_grouping,
      ordering: original.ordering,
      display_properties: original.display_properties,
      board_group_by: original.board_group_by,
      show_completed: original.show_completed,
      completed_filter: original.completed_filter,
      show_sub_items: original.show_sub_items,
      nested_sub_items: original.nested_sub_items,
      show_empty_groups: original.show_empty_groups,
      metadata: original.metadata,
    })
    .select()
    .single()

  if (error) return NextResponse.json({ error: error.message }, { status: 500 })

  return NextResponse.json({ view: duplicate }, { status: 201 })
}
