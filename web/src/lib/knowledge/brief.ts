import type { SupabaseClient } from '@supabase/supabase-js'
import { runUtilityTask, UtilitySessionError } from '@/lib/eve/utility/run-utility'
import { claimsVisibleToNobody } from '@/lib/knowledge/claim-visibility'
import { LABEL_TABLE } from '@/lib/knowledge/entity-registry'

/**
 * Compiled knowledge briefs — the machine-maintained "world model" per scope.
 *
 * A brief distills a scope's ranked claims into a short markdown document so
 * accumulated knowledge is CHEAP to load: the chat agent injects the workspace
 * brief into its system prompt, the MCP server exposes briefs as resources,
 * and package exports lead with them. Regenerated by the nightly knowledge
 * weaver whenever the underlying claim set changes (fingerprint-gated, so an
 * unchanged scope costs zero LLM calls).
 *
 * Cost posture: one call per CHANGED scope per night (~3K tokens in, ~1.2K
 * out), on the loop-engine default model (DeepSeek Flash — cheapest tier for
 * unattended work). Ranking, fingerprinting, and claim selection are pure
 * SQL/JS.
 */

/**
 * The scopes a brief can be compiled for.
 *
 * `workspace` and `package` are bespoke. Everything else is an ANCHOR scope:
 * its claims are exactly the claims carrying an `about` edge to that entity,
 * so `company` behaves identically to `project` and every branch below is
 * keyed by `scope.type` rather than written once per type. Adding `campaign`
 * to the registry's anchor types is then a one-line change HERE (this union
 * must stay literal so `scope_type` values and the migration 265 CHECK cannot
 * drift) and no change anywhere else in this file.
 */
export type BriefScope =
  | { type: 'workspace' }
  | { type: 'package'; id: string }
  | { type: AnchorScopeType; id: string }

/** Brief scopes whose claims are resolved through an `about` entity_link. */
export const ANCHOR_SCOPE_TYPES = ['project', 'company', 'campaign'] as const
export type AnchorScopeType = (typeof ANCHOR_SCOPE_TYPES)[number]

function isAnchorScope(
  scope: BriefScope,
): scope is { type: AnchorScopeType; id: string } {
  return (ANCHOR_SCOPE_TYPES as readonly string[]).includes(scope.type)
}

// Brief compilation runs on the knowledge surface's fixed model
// (SURFACE_MODELS), resolved per compile below.
const MAX_CLAIMS = 80
const MIN_CLAIMS = 3
/** Per anchor TYPE: how many anchors get a brief per workspace per run. */
const ANCHORS_PER_TYPE = 12
/** How many `about` edges are scanned to find those anchors. */
const ANCHOR_LINK_SCAN = 2000

// The compile rules (the session's system prompt) live with the utility agent's
// other prompts: src/lib/eve/utility/prompts.ts KNOWLEDGE_BRIEF_PROMPT.

export interface RankedClaim {
  id: string
  text: string
  type: string
  confidence: number | null
  confirmation: string
  created_at: string
  updated_at: string
}

/**
 * Fetch the scope's claims, confirmed-first then suggested, each ranked by
 * confidence + recency. Dismissed and superseded claims never make the brief.
 *
 * Briefs are workspace-readable documents compiled by unattended background
 * work, so claims sourced solely from private captures are excluded on every
 * branch (fail closed, NULL-requester semantics) — otherwise a nightly brief
 * would paraphrase a private meeting into a doc every member can open.
 *
 * `null` when any read failed: the caller must not mistake "couldn't read"
 * for "nothing left", because nothing left deletes the brief.
 */
async function fetchScopeClaims(
  supabase: SupabaseClient,
  workspaceId: string,
  scope: BriefScope,
): Promise<RankedClaim[] | null> {
  // Resolve the candidate claim ids for narrow scopes via the graph.
  let scopedIds: string[] | null = null
  if (isAnchorScope(scope)) {
    // Every anchor scope resolves the same way — the `about` edge IS what
    // "this claim belongs to that thing" means, whatever the thing is.
    const { data: links, error: linksError } = await supabase
      .from('entity_link')
      .select('source_id')
      .eq('workspace_id', workspaceId)
      .eq('source_type', 'claim')
      .eq('target_type', scope.type)
      .eq('target_id', scope.id)
      .limit(600)
    if (linksError) return null
    scopedIds = [...new Set((links ?? []).map((l) => l.source_id as string))]
    if (scopedIds.length === 0) return []
  } else if (scope.type === 'package') {
    // Packages have their own resolver so rules (types/since/confidence/
    // include_suggested) apply identically here, in get_package, and in the
    // export route. The visibility filter is applied HERE rather than inside
    // fetchPackageClaims because that resolver is shared with interactive,
    // user-scoped surfaces (get_package, the export route) which legitimately
    // see the requester's own private-sourced claims; only brief compilation
    // is unattended.
    const read = { failed: false }
    const packageClaims = await fetchPackageClaims(supabase, workspaceId, scope.id, MAX_CLAIMS, read)
    if (read.failed) return null
    return claimsVisibleToNobody(supabase, workspaceId, packageClaims)
  }

  const base = () => {
    let q = supabase
      .from('claim')
      .select('id, text, type, confidence, confirmation, created_at, updated_at')
      .eq('workspace_id', workspaceId)
      .eq('status', 'active')
      .order('confidence', { ascending: false, nullsFirst: false })
      .order('updated_at', { ascending: false })
    if (scopedIds) q = q.in('id', scopedIds.slice(0, 400))
    return q
  }

  const { data: confirmed, error: confirmedError } = await base()
    .eq('confirmation', 'confirmed')
    .limit(MAX_CLAIMS)
  if (confirmedError) return null
  const remaining = MAX_CLAIMS - (confirmed?.length ?? 0)
  const { data: suggested, error: suggestedError } =
    remaining > 0
      ? await base().eq('confirmation', 'suggested').limit(remaining)
      : { data: [] as RankedClaim[], error: null }
  if (suggestedError) return null

  return claimsVisibleToNobody(supabase, workspaceId, [
    ...(confirmed ?? []),
    ...(suggested ?? []),
  ] as RankedClaim[])
}

/**
 * Standing inclusion rules on a knowledge package (rules v2). Pins are
 * unconditional; rules govern only the claims THEY resolve.
 */
export interface PackageRules {
  /** Claims `about` these projects are included. */
  projects?: string[]
  /** Claim-type filter for rule-resolved claims (fact, decision_summary, ...). */
  types?: string[]
  /** Only rule-resolved claims updated at/after this ISO timestamp. */
  since?: string
  /** Confidence floor for rule-resolved claims. */
  min_confidence?: number
  /** false = rules contribute confirmed claims only (default true). */
  include_suggested?: boolean
}

/**
 * Resolve a package's membership into the two sets the filters distinguish:
 * pinned claim ids (explicit, never filtered) and rule-resolved claim ids
 * (subject to the rules' type/recency/confidence floors).
 */
async function resolvePackageClaimSets(
  supabase: SupabaseClient,
  workspaceId: string,
  packageId: string,
  read?: { failed: boolean },
): Promise<{ pinned: string[]; ruleResolved: string[]; rules: PackageRules }> {
  const pinned = new Set<string>()
  const projectIds: string[] = []

  const { data: items, error: itemsError } = await supabase
    .from('knowledge_package_item')
    .select('entity_type, entity_id')
    .eq('package_id', packageId)
    .eq('workspace_id', workspaceId)
    .limit(800)
  if (itemsError && read) read.failed = true
  for (const it of items ?? []) {
    if (it.entity_type === 'claim') pinned.add(it.entity_id as string)
    if (it.entity_type === 'project') projectIds.push(it.entity_id as string)
  }

  const { data: pkg, error: pkgError } = await supabase
    .from('knowledge_package')
    .select('rules')
    .eq('id', packageId)
    .eq('workspace_id', workspaceId)
    .maybeSingle()
  if (pkgError && read) read.failed = true
  const rules = (pkg?.rules ?? {}) as PackageRules
  for (const p of rules.projects ?? []) projectIds.push(p)

  const ruleResolved = new Set<string>()
  if (projectIds.length > 0) {
    const { data: links, error: linksError } = await supabase
      .from('entity_link')
      .select('source_id')
      .eq('workspace_id', workspaceId)
      .eq('source_type', 'claim')
      .eq('target_type', 'project')
      .in('target_id', [...new Set(projectIds)].slice(0, 20))
      .limit(800)
    if (linksError && read) read.failed = true
    for (const l of links ?? []) ruleResolved.add(l.source_id as string)
  }
  for (const id of pinned) ruleResolved.delete(id)

  return { pinned: [...pinned], ruleResolved: [...ruleResolved], rules }
}

/** Flat id union — membership without filters (used for fingerprinting). */
export async function resolvePackageClaimIds(
  supabase: SupabaseClient,
  workspaceId: string,
  packageId: string,
): Promise<string[]> {
  const { pinned, ruleResolved } = await resolvePackageClaimSets(
    supabase,
    workspaceId,
    packageId,
  )
  return [...pinned, ...ruleResolved]
}

/**
 * THE shared package-claims resolver — get_package, the export route, and
 * brief compilation all go through here so the rules are applied exactly once,
 * identically (the audit found min_confidence/include_suggested applied
 * inconsistently across surfaces).
 *
 * Semantics: pinned claims are unconditional (active + not-dismissed only);
 * rule-resolved claims additionally respect types / since / min_confidence /
 * include_suggested. Ranking: confirmed first, then confidence, then recency.
 */
export async function fetchPackageClaims(
  supabase: SupabaseClient,
  workspaceId: string,
  packageId: string,
  limit = MAX_CLAIMS,
  /** Set to `failed` when any read errored (brief compilation must tell it from "no claims"). */
  read?: { failed: boolean },
): Promise<RankedClaim[]> {
  const { pinned, ruleResolved, rules } = await resolvePackageClaimSets(
    supabase,
    workspaceId,
    packageId,
    read,
  )
  if (pinned.length === 0 && ruleResolved.length === 0) return []

  const baseQuery = (ids: string[], applyRules: boolean) => {
    let q = supabase
      .from('claim')
      .select('id, text, type, confidence, confirmation, created_at, updated_at')
      .eq('workspace_id', workspaceId)
      .eq('status', 'active')
      .neq('confirmation', 'dismissed')
      .in('id', ids.slice(0, 400))
      .order('confidence', { ascending: false, nullsFirst: false })
      .order('updated_at', { ascending: false })
      .limit(limit)
    if (applyRules) {
      if (rules.types?.length) q = q.in('type', rules.types)
      if (rules.since) q = q.gte('updated_at', rules.since)
      if (rules.min_confidence != null) q = q.gte('confidence', rules.min_confidence)
      if (rules.include_suggested === false) q = q.eq('confirmation', 'confirmed')
    }
    return q
  }

  const [pinnedRes, ruleRes] = await Promise.all([
    pinned.length ? baseQuery(pinned, false) : Promise.resolve({ data: [] }),
    ruleResolved.length ? baseQuery(ruleResolved, true) : Promise.resolve({ data: [] }),
  ])

  if (read && ((pinnedRes as { error?: unknown }).error || (ruleRes as { error?: unknown }).error)) read.failed = true
  const merged = [
    ...((pinnedRes.data ?? []) as RankedClaim[]),
    ...((ruleRes.data ?? []) as RankedClaim[]),
  ]
  merged.sort((a, b) => {
    const conf = (c: RankedClaim) => (c.confirmation === 'confirmed' ? 0 : 1)
    if (conf(a) !== conf(b)) return conf(a) - conf(b)
    const ca = a.confidence ?? -1
    const cb = b.confidence ?? -1
    if (ca !== cb) return cb - ca
    return a.updated_at < b.updated_at ? 1 : -1
  })
  return merged.slice(0, limit)
}

function fingerprintClaims(claims: RankedClaim[]): string {
  const material = claims
    .map((c) => `${c.id}:${c.updated_at}:${c.confirmation}`)
    .sort()
    .join('|')
  return crypto.createHash('sha256').update(material).digest('hex')
}

async function scopeLabel(
  supabase: SupabaseClient,
  workspaceId: string,
  scope: BriefScope,
): Promise<string> {
  if (isAnchorScope(scope)) {
    // Table and label rendering come from the entity registry, so a new
    // anchor type is labelled correctly with no edit here.
    const entity = LABEL_TABLE[scope.type]
    if (entity) {
      const { data } = await supabase
        .from(entity.table)
        .select(entity.columns)
        .eq('id', scope.id)
        .eq('workspace_id', workspaceId)
        .maybeSingle()
      const name = data ? entity.label(data as unknown as Record<string, unknown>) : ''
      if (name) return `${scope.type} "${name}"`
    }
    return `a ${scope.type}`
  }
  if (scope.type === 'package') {
    const { data } = await supabase
      .from('knowledge_package')
      .select('name, description')
      .eq('id', scope.id)
      .eq('workspace_id', workspaceId)
      .maybeSingle()
    return data?.name
      ? `knowledge package "${data.name}"${data.description ? ` (${data.description})` : ''}`
      : 'a knowledge package'
  }
  const { data } = await supabase
    .from('workspace')
    .select('name')
    .eq('id', workspaceId)
    .maybeSingle()
  return data?.name ? `workspace "${data.name}"` : 'the workspace'
}

/**
 * Generate (or skip) the brief for one scope. Returns what happened so the
 * caller can report counts. Fingerprint short-circuit means calling this
 * repeatedly on an unchanged scope is free.
 */
export async function generateBriefForScope(
  supabase: SupabaseClient,
  workspaceId: string,
  scope: BriefScope,
  planOwner: string | null = null,
): Promise<'updated' | 'skipped' | 'empty'> {
  const scopeId = scope.type === 'workspace' ? null : scope.id
  const claims = await fetchScopeClaims(supabase, workspaceId, scope)
  if (claims === null) {
    // A read failed: keep whatever brief the scope has and try again on the
    // next weave. Never delete on a failed read.
    console.warn(`[knowledge brief] claim read failed for ${scope.type} scope in ${workspaceId}; brief left as it was`)
    return 'skipped'
  }
  if (claims.length < MIN_CLAIMS) {
    // Too little left to say: delete the brief this scope had, rather than
    // keep serving text compiled from claims that are gone or now hidden
    // (mail, migration 341; a capture made private). The chat prompt, the
    // MCP resource and get_package all read this row. Only a genuine "fewer
    // than 3 readable claims" lands here; a failed read returned above.
    let stale = supabase
      .from('knowledge_brief')
      .delete()
      .eq('workspace_id', workspaceId)
      .eq('scope_type', scope.type)
    stale = scopeId === null ? stale.is('scope_id', null) : stale.eq('scope_id', scopeId)
    const { error: deleteError } = await stale
    if (deleteError) throw new Error(`knowledge brief: stale delete failed: ${deleteError.message}`)
    return 'empty'
  }

  const fingerprint = fingerprintClaims(claims)
  let existingQuery = supabase
    .from('knowledge_brief')
    .select('id, source_fingerprint')
    .eq('workspace_id', workspaceId)
    .eq('scope_type', scope.type)
  existingQuery =
    scopeId === null
      ? existingQuery.is('scope_id', null)
      : existingQuery.eq('scope_id', scopeId)
  const { data: existing } = await existingQuery.maybeSingle()
  if (existing?.source_fingerprint === fingerprint) return 'skipped'

  const label = await scopeLabel(supabase, workspaceId, scope)
  const lines = claims.map(
    (c) =>
      `- [${c.type}${c.confidence != null ? `, conf ${c.confidence}` : ''}${c.confirmation === 'confirmed' ? ', confirmed' : ', unconfirmed'}] ${c.text}`,
  )

  // Only a CHANGED scope reaches here: the fingerprint gate above returns
  // before any eve round trip. One task session on the eve utility agent, on
  // the knowledge surface's fixed model (SURFACE_MODELS). No user
  // identity exists on this path (workspace-scoped background work), so
  // Gateway attribution is feature + workspace only. Brief compilation logs no
  // usage row — it never did.
  //
  // Output stays capped at 1600 tokens, as the pre-port call sent: the
  // knowledge_brief kind carries the cap and the utility agent's step
  // resolver enforces it on the model call (src/lib/eve/utility/spec.ts).
  //
  // A reasoning model can spend the whole cap thinking and return no text.
  // generateText handed back '' for that (→ 'empty', and the weave moved on
  // to the next scope); eve fails the session instead. Map exactly that case
  // back to 'empty' — every other failure still throws, as before.
  let text: string
  try {
    ;({ text } = await runUtilityTask({
      kind: 'knowledge_brief',
      supabase,
      workspaceId,
      // A free owner's workspace (planOwner, the weaver's planOwnerOf):
      // compiled on the owner's own ChatGPT plan.
      userId: planOwner,
      chatgptPlan: planOwner !== null,
      message: `Scope: ${label}\n\nClaims (ranked, confirmed first):\n${lines.join('\n')}`,
    }))
  } catch (err) {
    if (err instanceof UtilitySessionError && err.isEmptyModelResponse) return 'empty'
    throw err
  }
  if (!text?.trim()) return 'empty'

  // Project briefs also point at the reference wiki (spec-type index docs
  // generated by reference ingestion). Appended deterministically — the LLM
  // never sees or invents these links.
  let content = text.trim()
  if (scope.type === 'project') {
    const { data: specs } = await supabase
      .from('document')
      .select('slug, title')
      .eq('workspace_id', workspaceId)
      .eq('project_id', scope.id)
      .eq('type', 'spec')
      .eq('status', 'active')
      // A brief is shared: never name someone's private document (369).
      .eq('visibility', 'workspace')
      .contains('frontmatter', { page_kind: 'index' })
      .limit(12)
    if (specs?.length) {
      content += `\n\n## Reference docs\n${specs
        .map((s) => `- [[${s.slug}]] — ${s.title}`)
        .join('\n')}`
    }
  }

  const now = new Date().toISOString()
  const { error } = await supabase.from('knowledge_brief').upsert(
    {
      workspace_id: workspaceId,
      scope_type: scope.type,
      scope_id: scopeId,
      content,
      claim_count: claims.length,
      source_fingerprint: fingerprint,
      generated_at: now,
      updated_at: now,
    },
    { onConflict: 'workspace_id,scope_type,scope_id' },
  )
  return error ? 'empty' : 'updated'
}

/** Fetch the workspace brief for prompt injection. Null when none exists yet. */
export async function getWorkspaceBrief(
  supabase: SupabaseClient,
  workspaceId: string,
): Promise<{ content: string; generated_at: string } | null> {
  const { data } = await supabase
    .from('knowledge_brief')
    .select('content, generated_at')
    .eq('workspace_id', workspaceId)
    .eq('scope_type', 'workspace')
    .is('scope_id', null)
    .maybeSingle()
  return data ? { content: data.content as string, generated_at: data.generated_at as string } : null
}

/**
 * Regenerate the workspace brief plus the briefs of projects and packages
 * whose claim sets plausibly changed. Fingerprint gating inside
 * generateBriefForScope makes over-inclusion cheap (a no-op scope costs two
 * queries, no LLM call).
 */
export async function regenerateWorkspaceBriefs(
  supabase: SupabaseClient,
  workspaceId: string,
  anchorTypes: readonly string[] = ['project'],
  planOwner: string | null = null,
): Promise<{ updated: number; skipped: number; empty: number }> {
  const out = { updated: 0, skipped: 0, empty: 0 }
  const tally = (r: 'updated' | 'skipped' | 'empty') => {
    out[r] += 1
  }

  tally(await generateBriefForScope(supabase, workspaceId, { type: 'workspace' }, planOwner))

  // Anchors with claims wired to them (the graph is the source of truth for
  // which anchors HAVE knowledge worth compiling). Per TYPE, not shared: the
  // cap exists to bound one type's brief-compile calls, and a shared cap would
  // let a workspace's many projects starve its companies of briefs entirely.
  for (const type of anchorTypes) {
    if (!(ANCHOR_SCOPE_TYPES as readonly string[]).includes(type)) continue
    const { data: links } = await supabase
      .from('entity_link')
      .select('target_id')
      .eq('workspace_id', workspaceId)
      .eq('source_type', 'claim')
      .eq('target_type', type)
      .limit(ANCHOR_LINK_SCAN)
    const ids = [...new Set((links ?? []).map((l) => l.target_id as string))].slice(
      0,
      ANCHORS_PER_TYPE,
    )
    for (const id of ids) {
      tally(
        await generateBriefForScope(
          supabase,
          workspaceId,
          {
            type: type as AnchorScopeType,
            id,
          },
          planOwner,
        ),
      )
    }
  }

  const { data: packages } = await supabase
    .from('knowledge_package')
    .select('id')
    .eq('workspace_id', workspaceId)
    .limit(12)
  for (const p of packages ?? []) {
    tally(await generateBriefForScope(supabase, workspaceId, { type: 'package', id: p.id as string }, planOwner))
  }

  return out
}
