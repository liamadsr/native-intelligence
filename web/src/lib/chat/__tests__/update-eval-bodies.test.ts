/**
 * The background updates the chat cases send (evals/chat-agent/evals/updates/bodies.ts)
 * are the server's own text: each is rebuilt here with buildHomeTurnBody from
 * the same fixed input and must match byte for byte. The cases can't import
 * the app, so the file is generated: run this test with WRITE_EVAL_BODIES=1
 * to write it again after a guidance or a line changes, and review the diff.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { buildHomeTurnBody } from '../home-turn'
import { buildTeammateReport } from '../teammate-report'
import type { PlannedGuestAsk } from '@/lib/guests/guest-ask-lines'

const FILE = join(process.cwd(), 'evals/chat-agent/evals/updates/bodies.ts')

/** A guest's ask, as gatherGuestAsks plans it. */
function guestAsk(ask: Omit<PlannedGuestAsk, 'guestId' | 'learned'>): string {
  return buildHomeTurnBody(`eval-${ask.askId.slice(0, 8)}`, 'guest_ask', {
    guestAsks: { asks: [{ ...ask, guestId: `g-${ask.askId.slice(0, 8)}`, learned: [] }], askIds: [ask.askId] },
  })!
}

const BODIES: Record<string, string> = {
  /** A Household guest asks for the owner's evening: free times may go to her, "he'll confirm". */
  guestDinner: guestAsk({
    askId: '7f0c2a51-6b3d-4e8a-9c1f-2d4e6a8b0c13',
    guestName: 'Mom',
    tier: 'household',
    times: 'shared',
    question: 'Is Liam around for dinner tonight at 6:30? Dad and I are in town.',
    createdAt: '2026-10-27T15:40:00.000Z',
  }),
  /** A colleague whose free/busy needs the owner's approval: no times before he answers. */
  guestCall: guestAsk({
    askId: '3c9e1d27-8a4f-4b6c-b0d2-5e7f9a1b3c48',
    guestName: 'Priya',
    tier: 'colleague',
    times: 'ask_first',
    question: 'Can Liam do a quick call at 4 today about the launch plan?',
    createdAt: '2026-10-27T15:41:00.000Z',
  }),
  /** An event: mail from someone they know that needs a reply. */
  event: buildHomeTurnBody('eval-event-1', 'event', {
    events: {
      lines: ['- Mail that needs a reply, from rita.okafor@globex-logistics.example: the Globex shipping contract, she asks for the signed SOW by Thursday [thread th_eval_globex_sow]'],
      eventIds: ['e-eval-1'],
    },
  })!,
  /** A helper's report that asks the person a question. */
  helperQuestion: buildHomeTurnBody('eval-report-1', 'helper_report', {
    reports: [
      buildTeammateReport({
        runId: 'run-eval-1',
        workItemId: 'wi-eval-1',
        workspaceId: 'ws-eval',
        status: 'needs_input',
        teammateId: null,
        teammateName: 'Assistant',
        title: 'Initech proposal draft',
        question: 'Should the Initech proposal quote the Growth or the Enterprise tier?',
      }),
    ],
  })!,
}

function render(): string {
  const entries = Object.entries(BODIES).map(([key, text]) => `  ${key}: ${JSON.stringify(text)},`)
  return [
    '/**',
    ' * Generated by src/lib/chat/__tests__/update-eval-bodies.test.ts (WRITE_EVAL_BODIES=1): the',
    ' * background updates the chat cases send, exactly as the server writes them. Do not edit by hand.',
    ' */',
    'export const BODIES = {',
    ...entries,
    '} as const',
    '',
  ].join('\n')
}

describe("the chat cases' background updates are the server's", () => {
  it('evals/chat-agent/evals/updates/bodies.ts matches buildHomeTurnBody', () => {
    const expected = render()
    if (process.env.WRITE_EVAL_BODIES === '1') writeFileSync(FILE, expected)
    expect(readFileSync(FILE, 'utf8')).toBe(expected)
  })
})
