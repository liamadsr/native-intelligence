#!/usr/bin/env node
/**
 * Regenerates src/lib/sky/time-zone-places.ts from the system tzdata: each
 * zone's principal city (zone1970.tab, or zone.tab where that is all there
 * is, as on macOS) as [lat, lon, country], coordinates rounded to one
 * decimal; and the legacy names browsers still report (Asia/Calcutta,
 * Europe/Kiev, ...) as aliases, found as zoneinfo files byte-identical to
 * exactly one listed zone. The sky route uses it to place a request that
 * has no IP geolocation by the browser's time zone.
 *
 *   node scripts/generate-sky-time-zones.mjs [/usr/share/zoneinfo]
 */

import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join, relative } from 'node:path'

const ROOT = process.argv[2] ?? '/usr/share/zoneinfo'
const OUT = new URL('../src/lib/sky/time-zone-places.ts', import.meta.url)
const REGIONS = /^(Africa|America|Antarctica|Arctic|Asia|Atlantic|Australia|Europe|Indian|Pacific)\//

const tabName = existsSync(join(ROOT, 'zone1970.tab')) ? 'zone1970.tab' : 'zone.tab'
const version = existsSync(join(ROOT, '+VERSION')) ? readFileSync(join(ROOT, '+VERSION'), 'utf8').trim() : 'unknown'

/** ±DDMM[SS] or ±DDDMM[SS] → decimal degrees. */
function coord(raw, degDigits) {
  const sign = raw[0] === '-' ? -1 : 1
  const d = Number(raw.slice(1, 1 + degDigits))
  const m = Number(raw.slice(1 + degDigits, 3 + degDigits))
  const s = raw.length > 3 + degDigits ? Number(raw.slice(3 + degDigits)) : 0
  return sign * (d + m / 60 + s / 3600)
}
const round1 = (v) => Math.round(v * 10) / 10 + 0

const places = new Map()
for (const line of readFileSync(join(ROOT, tabName), 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue
  const [codes, iso, zone] = line.split('\t')
  const m = /^([+-]\d{4,6})([+-]\d{5,7})$/.exec(iso)
  if (!m || !zone) continue
  const lat = coord(m[1], 2)
  const lon = coord(m[2], 3)
  places.set(zone, [round1(lat), round1(lon), codes.split(',')[0]])
}

// Renamed zones whose bytes match several listed zones (so the hash can't tell).
const RENAMED = {
  'Africa/Asmera': 'Africa/Asmara',
  'America/Coral_Harbour': 'America/Atikokan',
  'Asia/Rangoon': 'Asia/Yangon',
  'Pacific/Ponape': 'Pacific/Pohnpei',
  'Pacific/Truk': 'Pacific/Chuuk',
}

// Legacy names: a zoneinfo file with the same bytes as one listed zone (or,
// when several match, the only one in the same region).
const hashOf = (file) => createHash('sha256').update(readFileSync(file)).digest('hex')
const byHash = new Map()
for (const zone of places.keys()) {
  const file = join(ROOT, zone)
  if (!existsSync(file)) continue
  const h = hashOf(file)
  byHash.set(h, [...(byHash.get(h) ?? []), zone])
}
const region = (zone) => zone.split('/')[0]
function aliasTarget(zone, file) {
  if (RENAMED[zone] && places.has(RENAMED[zone])) return RENAMED[zone]
  const candidates = byHash.get(hashOf(file)) ?? []
  if (candidates.length === 1) return candidates[0]
  const local = candidates.filter((c) => region(c) === region(zone))
  return local.length === 1 ? local[0] : null
}
const aliases = new Map()
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const file = join(dir, name)
    if (statSync(file).isDirectory()) walk(file)
    else {
      const zone = relative(ROOT, file)
      if (!REGIONS.test(zone) || places.has(zone)) continue
      const target = aliasTarget(zone, file)
      if (target) aliases.set(zone, target)
    }
  }
}
walk(ROOT)

const sorted = (m) => [...m.entries()].sort(([a], [b]) => (a < b ? -1 : 1))
const body = [
  '/**',
  ` * Generated by scripts/generate-sky-time-zones.mjs from tzdata ${version} (${tabName}); do not edit.`,
  ' * Each zone\'s principal city as [lat, lon, country], rounded to one decimal, and the',
  ' * legacy names browsers still report as aliases of a listed zone.',
  ' */',
  '',
  'export const TIME_ZONE_PLACES: Readonly<Record<string, readonly [number, number, string]>> = {',
  ...sorted(places).map(([z, [lat, lon, cc]]) => `  '${z}': [${lat}, ${lon}, '${cc}'],`),
  '}',
  '',
  'export const TIME_ZONE_ALIASES: Readonly<Record<string, string>> = {',
  ...sorted(aliases).map(([z, t]) => `  '${z}': '${t}',`),
  '}',
  '',
].join('\n')
writeFileSync(OUT, body)
console.log(`${places.size} zones, ${aliases.size} aliases → ${OUT.pathname}`)
