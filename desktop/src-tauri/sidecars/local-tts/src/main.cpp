// ---- framed I/O ------------------------------------------------------------

int g_out_fd = -1;  // the real stdout; fd 1 is redirected to stderr
std::timed_mutex g_out_mu;

void
log(const char* fmt, ...) __attribute__((format(printf, 1, 2)));
void
log(const char* fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    std::vfprintf(stderr, fmt, ap);
    va_end(ap);
    std::fputc('\n', stderr);
    std::fflush(stderr);
}

bool
write_all(int fd, const void* data, size_t n) {
    const auto* p = static_cast<const uint8_t*>(data);
    while (n > 0) {
        const ssize_t w = ::write(fd, p, n);
        if (w < 0) {
            if (errno == EINTR)
                continue;
            return false;
        }
        p += w;
        n -= static_cast<size_t>(w);
    }
    return true;
}

bool
read_exact(int fd, void* data, size_t n) {
    auto* p = static_cast<uint8_t*>(data);
    while (n > 0) {
        const ssize_t r = ::read(fd, p, n);
        if (r == 0)
            return false;  // EOF
        if (r < 0) {
            if (errno == EINTR)
                continue;
            return false;
        }
        p += r;
        n -= static_cast<size_t>(r);
    }
    return true;
}

// One frame, written whole under the lock (header and body never interleave
// with another thread's frame).
void
write_frame(uint8_t kind, const void* head, size_t head_len, const void* body, size_t body_len) {
    uint8_t header[5];
    header[0] = kind;
    const uint32_t len = static_cast<uint32_t>(head_len + body_len);
    std::memcpy(header + 1, &len, 4);  // little-endian on every supported host
    std::lock_guard<std::timed_mutex> lock(g_out_mu);
    if (!write_all(g_out_fd, header, 5) || (head_len && !write_all(g_out_fd, head, head_len)) ||
        (body_len && !write_all(g_out_fd, body, body_len))) {
        // The app closed our stdout — nobody is listening any more.
        std::_Exit(0);
    }
}

// Exit now, but not halfway through a frame: wait for one being written (the
// worker's audio) unless the host has stopped reading and it can't finish.
[[noreturn]] void
exit_now() {
    const bool locked = g_out_mu.try_lock_for(std::chrono::milliseconds(100));
    (void)locked;
    std::_Exit(0);
}

void
send(const json::Object& msg) {
    const std::string body = msg.str();
    write_frame(kKindJson, nullptr, 0, body.data(), body.size());
}

void
send_audio(const float* samples, size_t n) {
    uint8_t head[5];
    head[0] = kAudioStream;
    std::memcpy(head + 1, &kSampleRate, 4);
    write_frame(kKindAudio, head, sizeof head, samples, n * sizeof(float));
}

void
send_error(const std::string& id, const std::string& code, const std::string& message, bool fatal) {
    json::Object msg;
    msg.add("type", "error");
    if (!id.empty())
        msg.add("id", id);
    send(msg.add("code", code).add("message", message).add("fatal", fatal));
}

struct InFrame {
    uint8_t kind = 0;
    std::vector<uint8_t> payload;
    uint32_t oversized = 0;  // a frame over kMaxFrameBytes: its length (payload holds its start)
};

// false on EOF (it ends the session). A frame over kMaxFrameBytes is read
// and dropped; only its first kOversizedKeep bytes are kept.
constexpr size_t kOversizedKeep = 512;
bool
read_frame(InFrame& f) {
    uint8_t header[5];
    if (!read_exact(STDIN_FILENO, header, 5))
        return false;
    uint32_t len;
    std::memcpy(&len, header + 1, 4);
    f.kind = header[0];
    f.oversized = 0;
    if (len > kMaxFrameBytes) {
        f.oversized = len;
        f.payload.resize(kOversizedKeep);
        if (!read_exact(STDIN_FILENO, f.payload.data(), kOversizedKeep))
            return false;
        uint8_t sink[64 * 1024];
        for (size_t left = len - kOversizedKeep; left > 0;) {
            const size_t n = left < sizeof sink ? left : sizeof sink;
            if (!read_exact(STDIN_FILENO, sink, n))
                return false;
            left -= n;
        }
        return true;
    }
    f.payload.resize(len);
    return len == 0 || read_exact(STDIN_FILENO, f.payload.data(), len);
}

// The "id" of the JSON object that starts at `s` (an oversized frame's first
// bytes; the host writes keys sorted, so "id" comes before "text"): the first
// "id" key right after '{' or ','. Inside a string a quote is escaped, so a
// key can't be matched there. "" if there is none.
std::string
id_from_prefix(const std::string& s) {
    auto skip_ws = [&s](size_t k) {
        while (k < s.size() && (s[k] == ' ' || s[k] == '\t' || s[k] == '\n' || s[k] == '\r'))
            k++;
        return k;
    };
    for (size_t at = s.find("\"id\""); at != std::string::npos; at = s.find("\"id\"", at + 1)) {
        size_t b = at;
        while (b > 0 && (s[b - 1] == ' ' || s[b - 1] == '\t' || s[b - 1] == '\n' || s[b - 1] == '\r'))
            b--;
        if (b == 0 || (s[b - 1] != '{' && s[b - 1] != ','))
            continue;
        size_t k = skip_ws(at + 4);
        if (k >= s.size() || s[k] != ':')
            continue;
        k = skip_ws(k + 1);
        if (k >= s.size() || s[k] != '"')
            continue;
        const size_t e = s.find('"', k + 1);
        if (e == std::string::npos)
            return "";
        const std::string id = s.substr(k + 1, e - k - 1);
        return id.find('\\') == std::string::npos ? id : "";
    }
    return "";
}

// The next JSON message's type ("" for audio, malformed or oversized frames);
// false at EOF. An oversized frame is answered here: text_too_long for its
// speak (when its id can be read), and the session goes on.
bool
read_message(InFrame& frame, json::Value& msg, std::string& type) {
    if (!read_frame(frame))
        return false;
    type.clear();
    if (frame.oversized) {
        log("dropped a frame of %u bytes (over the %u-byte limit)", frame.oversized, kMaxFrameBytes);
        if (frame.kind == kKindJson)
            send_error(id_from_prefix(std::string(frame.payload.begin(), frame.payload.end())), "text_too_long",
                       "a message of " + std::to_string(frame.oversized) + " bytes is over the " +
                           std::to_string(kMaxFrameBytes) + "-byte limit",
                       false);
        return true;
    }
    if (frame.kind != kKindJson)
        return true;
    if (!json::parse(reinterpret_cast<const char*>(frame.payload.data()), frame.payload.size(), msg)) {
        log("ignoring a malformed JSON message");
        return true;
    }
    type = msg.str("type");
    return true;
}

