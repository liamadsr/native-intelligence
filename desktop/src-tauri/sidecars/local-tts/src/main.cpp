// dial8-local-tts — the local-tts module sidecar.
//
// Wraps PocketTTS.cpp (Kyutai's Pocket TTS on ONNX Runtime) through its C API
// and speaks Dial8's local-module protocol v1 on stdin/stdout (see
// src-tauri/src/modules/protocol.rs):
//
//   frame  = kind:u8  length:u32le  payload
//   kind 1 = JSON message, kind 2 = audio (stream:u8, rate:u32le, f32le[])
//
// Session:
//   → hello {module, protocol, version}
//   ← configure {assets:{flow_lm_main, flow_lm_flow, mimi_decoder,
//                text_conditioner, tokenizer, bos_before_voice},
//                threads?=2, lsdSteps?=8, warmup?=false, voice?,
//                options?:{name: number|bool}}
//                                    options: override kGenerationDefaults by
//                                    name (the bench; the app sends none)
//   → ready {voices}                 (or error {code, message, fatal:true})
//   ← speak {id, text, voice?, trimLead?}
//                                    queued; spoken in order, one at a time.
//                                    trimLead: speech starts from silence, so
//                                    drop the model's lead-in (LeadTrim)
//   → started {id}, audio frames (stream 0, 24 kHz, as the decoder produces
//     them: one or a few 80 ms frames each),
//     done {id, audioSeconds, truncated?}  (truncated: a piece ran to its
//                                    frame cap without the model ending it)
//                                    (or error {id?, code, message, fatal:false};
//                                    a frame over 1 MiB is dropped with
//                                    text_too_long, and the session goes on)
//   ← cancel                         stop the utterance, drop the queue
//   → cancelled {ids}                no audio for those ids follows it
//   ← ping → pong;  shutdown or stdin EOF → exit at once
//
// configure.voice (optional, default: the catalogue's default) is conditioned
// before ready, so its first speak starts as fast as the rest; another voice's
// first speak takes ~0.1 s longer, once. Warm-up (configure.warmup): speak one
// short phrase, discard it, send ready, then wait for stdin EOF and exit — the
// host's enable flow.
//
// Voices are compiled in (voices/voices.json + <id>.emb, embedded by
// build.sh) and picked by id; the voice-cloning encoder is never loaded.
// Text arrives normalized by the host (numbers, symbols) and is spoken as is,
// in pieces of at most ~30 words (split_chunks): the model loses its place in
// longer runs. Every piece is spoken under the speak's one id.

